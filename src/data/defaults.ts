/**
 * Determine which month in the 3-month period a date belongs to
 */
export function getExpenseMonth(dateStr: string, settings: ThreeMonthPeriodSettings): string {
  if (!dateStr) return 'Other';
  const target = dateStr.trim();
  
  if (target >= settings.month1.startDate && target <= settings.month1.endDate) {
    return 'Month 1';
  }
  if (target >= settings.month2.startDate && target <= settings.month2.endDate) {
    return 'Month 2';
  }
  if (target >= settings.month3.startDate && target <= settings.month3.endDate) {
    return 'Month 3';
  }
  return 'Outside Period';
}

